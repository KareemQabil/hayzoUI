#!/usr/bin/env node
// Validates every data file against the schema of its `kind`, and checks the conventions in docs/DATA_MODEL.md.
//   node tools/validate.mjs                 all of data/
//   node tools/validate.mjs data/regions    one directory (or file)
//   node tools/validate.mjs --sources       also rewrite docs/SOURCES.md from the provenance of every file
// Exit code 1 when any file fails.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SCHEMA_DIR = path.join(ROOT, 'data', 'schema')
const args = process.argv.slice(2)
const writeSources = args.includes('--sources')
const targets = args.filter((a) => !a.startsWith('--'))

const ajv = new Ajv2020({ allErrors: true, strict: false })
addFormats(ajv)
const kinds = new Set()
for (const file of fs.readdirSync(SCHEMA_DIR).filter((f) => f.endsWith('.schema.json'))) {
  const schema = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, file), 'utf8'))
  if (schema.$id !== file) fail(`data/schema/${file}`, [`$id must be "${file}"`])
  ajv.addSchema(schema)
  if (file !== 'common.schema.json') kinds.add(file.replace('.schema.json', ''))
}

function walk(p, out = []) {
  const stat = fs.statSync(p)
  if (stat.isFile()) {
    if (p.endsWith('.json') && !p.startsWith(SCHEMA_DIR)) out.push(p)
    return out
  }
  for (const entry of fs.readdirSync(p).sort()) {
    const child = path.join(p, entry)
    if (child === SCHEMA_DIR) continue
    walk(child, out)
  }
  return out
}

let failed = 0
function fail(rel, messages) {
  failed++
  console.error(`✗ ${rel}`)
  for (const m of messages.slice(0, 12)) console.error(`    ${m}`)
  if (messages.length > 12) console.error(`    … ${messages.length - 12} more`)
}

const files = (targets.length ? targets : ['data']).flatMap((t) => walk(path.resolve(ROOT, t)))
const byKind = new Map()
const sources = new Map()

for (const file of files) {
  const rel = path.relative(ROOT, file)
  let doc
  try {
    doc = JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch (error) {
    fail(rel, [`not valid JSON: ${error.message}`])
    continue
  }
  if (!kinds.has(doc.kind)) {
    fail(rel, [`unknown kind ${JSON.stringify(doc.kind)}; expected one of: ${[...kinds].join(', ')}`])
    continue
  }
  const validate = ajv.getSchema(`${doc.kind}.schema.json`)
  const problems = validate(doc) ? [] : validate.errors.map((e) => `${e.instancePath || '/'} ${e.message}${e.params?.additionalProperty ? ` (${e.params.additionalProperty})` : ''}`)

  const p = doc.provenance
  if (p) {
    if (p.method !== 'authored' && !(p.sources?.length > 0)) problems.push('/provenance/sources must list at least one source unless method is "authored"')
    if (p.method === 'extracted' && !p.script) problems.push('/provenance/script is required when method is "extracted"')
    if (p.script && !fs.existsSync(path.join(ROOT, p.script))) problems.push(`/provenance/script points to a missing file: ${p.script}`)
    if (p.confidence === 'verified' && p.method === 'researched' && !(p.sources?.length > 0)) problems.push('verified research needs a primary source')
    for (const s of p.sources ?? []) {
      const key = `${s.name}|${s.license}`
      const entry = sources.get(key) ?? { name: s.name, license: s.license, url: s.url, versions: new Set(), files: 0 }
      if (s.version) entry.versions.add(s.version)
      entry.files++
      sources.set(key, entry)
    }
  }
  if (fs.statSync(file).size > 6_000_000) problems.push('file is larger than 6 MB; split it')

  if (problems.length) fail(rel, problems)
  const stats = byKind.get(doc.kind) ?? { files: 0, verified: 0, 'needs-review': 0, unverified: 0 }
  stats.files++
  if (p?.confidence in stats) stats[p.confidence]++
  byKind.set(doc.kind, stats)
}

console.log('\nkind              files  verified  needs-review  unverified')
for (const [k, s] of [...byKind].sort()) console.log(`${k.padEnd(18)}${String(s.files).padStart(5)}${String(s.verified).padStart(10)}${String(s['needs-review']).padStart(14)}${String(s.unverified).padStart(12)}`)
console.log(`\n${files.length} files, ${failed} failed`)

if (writeSources) {
  const rows = [...sources.values()].sort((a, b) => a.name.localeCompare(b.name))
  const md = ['# Sources', '', 'Generated by `node tools/validate.mjs --sources` from the provenance of every data file. Do not edit by hand.', '', '| Source | License | Versions read | Files |', '|---|---|---|---|', ...rows.map((r) => `| [${r.name}](${r.url}) | ${r.license} | ${[...r.versions].join(', ') || '—'} | ${r.files} |`), '']
  fs.writeFileSync(path.join(ROOT, 'docs', 'SOURCES.md'), md.join('\n'))
  console.log(`wrote docs/SOURCES.md (${rows.length} sources)`)
}
process.exit(failed ? 1 : 0)
