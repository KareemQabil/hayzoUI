const LABEL = 'IDREF of the visible label; otherwise aria-label'
const gridNavKeys = (kind) => {
  const layout = kind === 'layout'
  const g = layout ? 'layout grid: navigation' : 'data grid: navigation'
  const o = layout ? opt : {}
  return [
    m('ArrowRight', layout ? 'Move focus one cell toward the end of the row; at the row end optionally wrap to the first cell of the next row; stay on the last cell of the grid.' : 'Move focus one cell toward the end of the row; stay if already on the last cell of the row.', { group: g, decision: 'grid-cell-navigation' }),
    m('ArrowLeft', layout ? 'Move focus one cell toward the start of the row; at the row start optionally wrap to the last cell of the previous row; stay on the first cell of the grid.' : 'Move focus one cell toward the start of the row; stay if already on the first cell of the row.', { group: g, decision: 'grid-cell-navigation' }),
    n('ArrowDown', layout ? 'Move focus one cell down; at the column bottom optionally wrap to the top of the next column; stay on the last cell of the grid.' : 'Move focus one cell down; stay if already in the last row.', { group: g }),
    n('ArrowUp', layout ? 'Move focus one cell up; at the column top optionally wrap to the bottom of the previous column; stay on the first cell of the grid.' : 'Move focus one cell up; stay if already in the first row.', { group: g }),
    n('PageDown', 'Move focus down by an author-defined number of rows, scrolling so the last visible row becomes one of the first; stay if in the last row.', { group: g, ...o }),
    n('PageUp', 'Move focus up by an author-defined number of rows, scrolling so the first visible row becomes one of the last; stay if in the first row.', { group: g, ...o }),
    n('Home', layout ? 'Move focus to the first cell of the current row; with a single column or fewer than three cells per row, optionally to the first cell of the grid.' : 'Move focus to the first cell of the current row.', { group: g }),
    n('End', layout ? 'Move focus to the last cell of the current row; with a single column or fewer than three cells per row, optionally to the last cell of the grid.' : 'Move focus to the last cell of the current row.', { group: g }),
    n('Control+Home', 'Move focus to the first cell of the first row.', { group: g, ...o }),
    n('Control+End', 'Move focus to the last cell of the last row (the last row in the DOM when rows load on demand).', { group: g, ...o }),
  ]
}
