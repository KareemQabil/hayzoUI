// Multi-selection keys shared by listbox and tree ("option"/"node").
const multiSelect = (item, extra = {}) => {
  const R = 'multi-select: recommended model (no modifier needed)'
  const A = 'multi-select: alternative model (plain arrows collapse the selection)'
  const common = (g) => [
    n('Shift+Space', `Select the contiguous ${item}s from the most recently selected one to the focused one.`, { group: g, ...opt, ...extra }),
    n('Control+Shift+Home', `Select the focused ${item} and every ${item} up to the first; optionally move focus to the first.`, { group: g, ...opt, ...extra }),
    n('Control+Shift+End', `Select the focused ${item} and every ${item} down to the last; optionally move focus to the last.`, { group: g, ...opt, ...extra }),
    n('Control+A', `Select every ${item}; optionally, when all are selected, unselect all.`, { group: g, ...opt, ...extra }),
  ]
  return [
    n('Space', `Toggle the selection of the focused ${item}.`, { group: R, ...extra }),
    n('Shift+ArrowDown', `Move focus to the next ${item} and toggle its selection.`, { group: R, ...opt, ...extra }),
    n('Shift+ArrowUp', `Move focus to the previous ${item} and toggle its selection.`, { group: R, ...opt, ...extra }),
    ...common(R),
    n('Shift+ArrowDown', `Move focus to the next ${item} and toggle its selection.`, { group: A, ...extra }),
    n('Shift+ArrowUp', `Move focus to the previous ${item} and toggle its selection.`, { group: A, ...extra }),
    n('Control+ArrowDown', `Move focus to the next ${item} without changing selection.`, { group: A, ...extra }),
    n('Control+ArrowUp', `Move focus to the previous ${item} without changing selection.`, { group: A, ...extra }),
    n('Control+Space', `Toggle the selection of the focused ${item}.`, { group: A, ...extra }),
    ...common(A),
  ]
}
